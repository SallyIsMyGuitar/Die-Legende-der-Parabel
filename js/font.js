  var LINE = 10;   // Zeilenhöhe in Pixeln

  function glyph(ch) {
    return G[ch] || G['?'];
  }

  function charWidth(ch) {
    return glyph(ch)[0].length;
  }

  function width(str) {
    var w = 0;
    for (var i = 0; i < str.length; i++) w += charWidth(str.charAt(i)) + 1;
    return Math.max(0, w - 1);
  }

  // Text zeichnen; Rückgabe: Breite in Pixeln
  function draw(ctx, str, x, y, color) {
    ctx.fillStyle = color;
    var cx = Math.round(x);
    y = Math.round(y);
    for (var i = 0; i < str.length; i++) {
      var g = glyph(str.charAt(i));
      for (var j = 0; j < g.length; j++) {
        for (var k = 0; k < g[j].length; k++) {
          if (g[j].charAt(k) === '#') ctx.fillRect(cx + k, y + j, 1, 1);
        }
      }
      cx += g[0].length + 1;
    }
    return cx - x;
  }

  // Zeilenumbruch an Wortgrenzen
  function wrap(text, maxW) {
    var words = text.split(' '), lines = [], line = '';
    for (var i = 0; i < words.length; i++) {
      var test = line ? line + ' ' + words[i] : words[i];
      if (width(test) > maxW && line) {
        lines.push(line);
        line = words[i];
      } else {
        line = test;
      }
    }
    if (line) lines.push(line);
    return lines;
  }

  return { draw: draw, width: width, wrap: wrap, LINE: LINE };
